#!/bin/bash
# Build the signed release APK for the Android companion app.
# Requires: JDK 17+ (system JDK 21), network access to dl.google.com / maven.google.com.
# The Android SDK is provisioned into /tmp (AGP auto-downloads platform + build-tools
# because license hashes are pre-accepted below). Nothing here writes secrets into git.
set -euo pipefail

SDK=/tmp/android-sdk
GRADLE_ZIP=/tmp/gradle-8.9-bin.zip
PROJECT_ANDROID=/home/z/my-project/android-companion

# 1. Accept SDK licenses so AGP can auto-install platform-35 / build-tools.
mkdir -p "$SDK/licenses"
echo "24333f8a63b6825ea9c5514f83c2829b004d1fee" > "$SDK/licenses/android-sdk-license"
echo "84831b9409646a918e30573bab4c9c91346d8abd" > "$SDK/licenses/android-sdk-preview-license"

# 2. Provision Gradle 8.9 (AGP 8.5.2-compatible, supports the system JDK 21).
if [ ! -f "$GRADLE_ZIP" ]; then
  echo "[build] downloading gradle 8.9 ..."
  curl -sSL -o "$GRADLE_ZIP" "https://services.gradle.org/distributions/gradle-8.9-bin.zip"
fi
[ -d /tmp/gradle-8.9 ] || unzip -q "$GRADLE_ZIP" -d /tmp

# 3. Build the signed release APK (keystore.properties generated by gen-keystore step).
export ANDROID_HOME="$SDK"
export GRADLE_USER_HOME=/tmp/gradle-home
cd "$PROJECT_ANDROID"
/tmp/gradle-8.9/bin/gradle --no-daemon assembleRelease \
  -PserverUrl="https://n-0e1a0994-32ba-4e3f-a5fa-3377ead9995b.space-z.ai"

echo "BUILD_OK"
ls -la app/build/outputs/apk/release/ || true
